package store

import (
	"context"
	"database/sql"
	"encoding/json"
	"errors"
	"fmt"

	"github.com/jackc/pgx/v5/pgconn"
)

const pgUniqueViolation = "23505"

// maxSaveAttempts is how often SaveResult retries when two submissions for the
// same seed race for the same attempt number.
const maxSaveAttempts = 3

// SavedFinding is what the player submitted for one anomaly plus how it was
// graded. It never contains the correct answers.
type SavedFinding struct {
	SourceIP      string `json:"source_ip"`
	Endpoint      string `json:"endpoint"`
	AnomalyType   string `json:"anomaly_type"`
	Correct       bool   `json:"correct"`
	SourceIPOK    bool   `json:"source_ip_ok"`
	EndpointOK    bool   `json:"endpoint_ok"`
	AnomalyTypeOK bool   `json:"anomaly_type_ok"`
}

// Result is one graded singleplayer submission.
type Result struct {
	UserID      string
	Seed        string
	Environment string
	Difficulty  string
	Score       int
	Matched     int
	Total       int
	Correct     bool
	Findings    []SavedFinding
	// ClassroomID is set when the game was played inside a classroom ("" otherwise).
	ClassroomID string
}

// HistoryItem is one row of the history list.
type HistoryItem struct {
	ID              string          `json:"id"`
	Seed            string          `json:"seed"`
	Environment     string          `json:"environment"`
	Difficulty      string          `json:"difficulty"`
	AttemptNumber   int             `json:"attempt_number"`
	Score           int             `json:"score"`
	Matched         int             `json:"matched"`
	Total           int             `json:"total"`
	Correct         bool            `json:"correct"`
	DurationSeconds *int            `json:"duration_seconds"`
	CreatedAt       string          `json:"created_at"`
	Findings        json.RawMessage `json:"findings"`
	// RoomCode is set when the answer was submitted in a multiplayer room.
	RoomCode string `json:"room_code,omitempty"`
}

// RecordStart remembers when this user created this simulation. Creating the
// same simulation again restarts the clock.
//
// classroomID is "" for a normal game. A classroom game's clock is never
// restarted: the seed is generated by the server, and re-creating it through
// the normal singleplayer route must not give anyone a shorter time.
func RecordStart(ctx context.Context, db *sql.DB, userID, seed, environment, difficulty, classroomID string) error {
	_, err := db.ExecContext(ctx, `
		INSERT INTO public.singleplayer_runs (user_id, seed, environment, difficulty, started_at, classroom_id)
		VALUES ($1::uuid, $2, $3, $4, NOW(), NULLIF($5, '')::uuid)
		ON CONFLICT (user_id, seed, environment, difficulty)
		DO UPDATE SET started_at = NOW(), classroom_id = EXCLUDED.classroom_id
		WHERE public.singleplayer_runs.classroom_id IS NULL
	`, userID, seed, environment, difficulty, classroomID)
	return err
}

// SaveResult stores one graded submission and returns its attempt number
// (1 for the first submission on that seed by that user, then 2, 3, ...).
// The time taken is measured in the database, from the recorded start to now;
// it is NULL if no start was recorded.
func SaveResult(ctx context.Context, db *sql.DB, res Result) (int, error) {
	findings, err := json.Marshal(res.Findings)
	if err != nil {
		return 0, err
	}
	if res.Findings == nil {
		findings = []byte("[]")
	}

	const query = `
		INSERT INTO public.singleplayer_results
			(user_id, seed, environment, difficulty, attempt_number,
			 score, matched, total, correct, findings, started_at, duration_seconds, classroom_id)
		SELECT $1::uuid, $2, $3, $4,
			COALESCE((SELECT MAX(attempt_number) FROM public.singleplayer_results
			          WHERE user_id = $1::uuid AND seed = $2), 0) + 1,
			$5, $6, $7, $8, $9::jsonb,
			r.started_at,
			CASE WHEN r.started_at IS NULL THEN NULL
			     ELSE GREATEST(0, EXTRACT(EPOCH FROM (NOW() - r.started_at))::int) END,
			NULLIF($10, '')::uuid
		FROM (SELECT 1) AS one
		LEFT JOIN public.singleplayer_runs r
			ON r.user_id = $1::uuid AND r.seed = $2
			AND r.environment = $3 AND r.difficulty = $4
		RETURNING attempt_number
	`

	for try := 0; try < maxSaveAttempts; try++ {
		var attempt int
		err = db.QueryRowContext(ctx, query,
			res.UserID, res.Seed, res.Environment, res.Difficulty,
			res.Score, res.Matched, res.Total, res.Correct, string(findings), res.ClassroomID,
		).Scan(&attempt)
		if err == nil {
			return attempt, nil
		}

		// Someone else took this attempt number a moment ago: try again.
		var pgErr *pgconn.PgError
		if errors.As(err, &pgErr) && pgErr.Code == pgUniqueViolation {
			continue
		}
		return 0, err
	}
	return 0, fmt.Errorf("could not allocate an attempt number: %w", err)
}

// ListResults returns the user's newest submissions first. It also reports
// whether more rows exist after this page.
func ListResults(ctx context.Context, db *sql.DB, userID string, limit, offset int) ([]HistoryItem, bool, error) {
	rows, err := db.QueryContext(ctx, `
		SELECT id::text, seed, environment, difficulty, attempt_number,
		       score, matched, total, correct, duration_seconds,
		       to_char(created_at AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'),
		       findings::text, COALESCE(room_code, '')
		FROM public.singleplayer_results
		WHERE user_id = $1::uuid
		ORDER BY created_at DESC, attempt_number DESC
		LIMIT $2 OFFSET $3
	`, userID, limit+1, offset)
	if err != nil {
		return nil, false, err
	}
	defer rows.Close()

	items := make([]HistoryItem, 0, limit)
	for rows.Next() {
		var it HistoryItem
		var duration sql.NullInt64
		var findings string
		if err := rows.Scan(&it.ID, &it.Seed, &it.Environment, &it.Difficulty, &it.AttemptNumber,
			&it.Score, &it.Matched, &it.Total, &it.Correct, &duration,
			&it.CreatedAt, &findings, &it.RoomCode); err != nil {
			return nil, false, err
		}
		if duration.Valid {
			d := int(duration.Int64)
			it.DurationSeconds = &d
		}
		it.Findings = json.RawMessage(findings)
		items = append(items, it)
	}
	if err := rows.Err(); err != nil {
		return nil, false, err
	}

	more := len(items) > limit
	if more {
		items = items[:limit]
	}
	return items, more, nil
}
